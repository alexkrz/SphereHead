''' Generate single samples from a projected latent (see projector.py) at a given
camera angle (yaw/pitch), instead of rendering a full 360 degree trajectory as in
gen_videos_proj_withseg.py.

Uses either:
  1) the finetuned generator pickle produced by projector.py
     ('fintuned_generator.pkl'), together with the corresponding
     'projected_w.npz';
  2) or the original pretrained network pickle with the projected latent npz.

Example usage:

python gen_samples_from_angle.py \
    --network output/<model>/<image>/fintuned_generator.pkl \
    --latent  output/<model>/<image>/projected_w.npz \
    --yaw 30 --pitch 0 \
    --cfg Head --outdir out
'''

import os
import re
from typing import List, Optional, Tuple, Union

import click
import dnnlib
import numpy as np
import PIL.Image
import torch

import legacy

from camera_utils import LookAtPoseSampler
from torch_utils import misc
from training.triplane import TriPlaneGenerator

#----------------------------------------------------------------------------

def parse_float_list(s: Union[str, List[float]]) -> List[float]:
    '''Parse a comma separated list of floats (degrees) or a single float value.

    Example: '0,15,-30' returns [0.0, 15.0, -30.0]
    '''
    if isinstance(s, list): return s
    return [float(p) for p in s.split(',') if p != '']

#----------------------------------------------------------------------------

def render_angle(
    G,
    ws: torch.Tensor,                                # [1, num_ws, w_dim]
    yaw_deg: float,
    pitch_deg: float,
    delta_c: Optional[torch.Tensor] = None,          # [1, 3] self-adaptive pose offset
    cfg: str = 'Head',
    image_mode: str = 'image',
    device=torch.device('cuda'),
    ):
    """Render the given latent at a single camera angle (degrees).

    Angle convention matches gen_videos_proj_withseg.py:
    the front view is yaw = pitch = 0, mapped to spherical angles (pi/2, pi/2).
    """
    if cfg == "Head":
        cam_pivot = torch.tensor([0, 0, 0], device=device)
        cam_radius = 2.75
    else: # FFHQ
        cam_pivot = torch.tensor([0, 0, 0.2], device=device)
        cam_radius = 2.7

    yaw_rad = np.pi / 2 + yaw_deg / 180 * np.pi
    pitch_rad = np.pi / 2 + pitch_deg / 180 * np.pi
    cam2world_pose = LookAtPoseSampler.sample(yaw_rad, pitch_rad, cam_pivot, radius=cam_radius, device=device)
    intrinsics = torch.tensor([[4.2647, 0, 0.5], [0, 4.2647, 0.5], [0, 0, 1]], device=device)
    c = torch.cat([cam2world_pose.reshape(-1, 16), intrinsics.reshape(-1, 9)], 1)

    # fix delta_c (self-adaptive camera pose offset), as in gen_videos_proj_withseg.py
    if delta_c is not None:
        c[:,3] += delta_c[:,0]
        c[:,7] += delta_c[:,1]
        c[:,11] += delta_c[:,2]

    img = G.synthesis(ws=ws, c=c, noise_mode='const')[image_mode]

    if image_mode == 'image_depth':
        img = -img
        img = (img - img.min()) / (img.max() - img.min()) * 2 - 1

    img = (img.permute(0, 2, 3, 1) * 127.5 + 128).clamp(0, 255).to(torch.uint8)
    return img[0].cpu().numpy()

#----------------------------------------------------------------------------

def compute_delta_c(G, cfg: str = 'Head', device=torch.device('cuda'), num_samples: int = 10000):
    """Compute the self-adaptive camera pose offset (delta_c) from the mean z,
    following gen_videos_proj_withseg.py."""
    camera_lookat_point = torch.tensor([0, 0, 0.2], device=device) if cfg == 'FFHQ' else torch.tensor([0, 0, 0], device=device)
    cam2world_pose = LookAtPoseSampler.sample(3.14/2, 3.14/2, camera_lookat_point, radius=2.7, device=device)
    intrinsics = torch.tensor([[4.2647, 0, 0.5], [0, 4.2647, 0.5], [0, 0, 1]], device=device)
    c = torch.cat([cam2world_pose.reshape(-1, 16), intrinsics.reshape(-1, 9)], 1)

    z_samples = np.random.RandomState(123).randn(num_samples, G.z_dim)
    delta_c = G.t_mapping(torch.from_numpy(np.mean(z_samples, axis=0, keepdims=True)).to(device), c, truncation_psi=1.0, truncation_cutoff=None, update_emas=False)
    delta_c = torch.squeeze(delta_c, 1)
    return delta_c

#----------------------------------------------------------------------------

def load_latent(path: str, device=torch.device('cuda')) -> torch.Tensor:
    """Load a projected W vector saved by projector.py ('projected_w.npz').
    Also accepts the latent directory, in which case 'projected_w.npz' is used."""
    if os.path.isdir(path):
        path = os.path.join(path, 'projected_w.npz')
    w = np.load(path)['w'] # [1, num_ws, w_dim]
    ws = torch.tensor(w, dtype=torch.float32, device=device)
    if ws.dim() == 2:
        ws = ws.unsqueeze(0)
    return ws

#----------------------------------------------------------------------------

@click.command()
@click.option('--network', 'network_pkl', help='Network pickle filename: the "fintuned_generator.pkl" generated by projector.py, or the original pretrained network pickle.', required=True, metavar='FILE')
@click.option('--latent', help='Projected latent saved by projector.py ("projected_w.npz"), or its directory.', required=True, metavar='FILE|DIR')
@click.option('--outdir', help='Where to save the output images', type=str, required=True, metavar='DIR')
@click.option('--yaw', 'yaws', type=parse_float_list, help='Yaw angle(s) in degrees, relative to the front view (0 = front). comma-separated list allowed.', default='0', show_default=True)
@click.option('--pitch', 'pitchs', type=parse_float_list, help='Pitch angle(s) in degrees, relative to the front view (0 = front). comma-separated list allowed.', default='0', show_default=True)
@click.option('--cfg', help='Config', type=click.Choice(['FFHQ', 'Head']), required=False, metavar='STR', default='Head', show_default=True)
@click.option('--image_mode', help='Image mode', type=click.Choice(['image', 'image_depth', 'image_raw']), required=False, metavar='STR', default='image', show_default=True)
@click.option('--no-delta-c', 'no_delta_c', help='Disable the self-adaptive camera pose offset (delta_c).', type=bool, default=False, show_default=True)
@click.option('--sample_mult', 'sampling_multiplier', type=float, help='Multiplier for depth sampling in volume rendering', default=1, show_default=True)
@click.option('--nrr', type=int, help='Neural rendering resolution override', default=None, show_default=True)
@click.option('--ray-start', type=float, help='Override rendering_kwargs["ray_start"] (projector.py uses 2.35). Only applied when passing the original pretrained network pickle.', default=None, show_default=False)

def generate_images(
    network_pkl: str,
    latent: str,
    outdir: str,
    yaws: List[float],
    pitchs: List[float],
    cfg: str,
    image_mode: str,
    no_delta_c: bool,
    sampling_multiplier: float,
    nrr: Optional[int],
    ray_start: Optional[float],
):
    """Generate single samples from a projected latent at a given angle.

    Examples:

    \b
    # Render the projected identity at yaw=30, pitch=0 (front view):
    python gen_samples_from_angle.py --outdir=out --yaw 30 --pitch 0 \\
        --network output/proj/image/fintuned_generator.pkl \\
        --latent output/proj/image/projected_w.npz

    # Grid of angles (one image per (yaw, pitch) pair):
    python gen_samples_from_angle.py --outdir=out --yaw 0,45,90 --pitch 0,-15 \\
        --cfg Head --network <pkl> --latent <projected_w.npz>
    """

    print('Loading networks from "%s"...' % network_pkl)
    device = torch.device('cuda:0')
    with dnnlib.util.open_url(network_pkl) as f:
        G = legacy.load_network_pkl(f)['G_ema'].to(device) # type: ignore

    G_new = TriPlaneGenerator(*G.init_args, **G.init_kwargs).eval().requires_grad_(False).to(device)
    misc.copy_params_and_buffers(G, G_new, require_all=True)
    G_new.neural_rendering_resolution = G.neural_rendering_resolution
    G_new.rendering_kwargs = G.rendering_kwargs
    G = G_new

    G.rendering_kwargs['depth_resolution'] = int(G.rendering_kwargs['depth_resolution'] * sampling_multiplier)
    G.rendering_kwargs['depth_resolution_importance'] = int(G.rendering_kwargs['depth_resolution_importance'] * sampling_multiplier)
    if nrr is not None: G.neural_rendering_resolution = nrr
    if ray_start is not None:
        G.rendering_kwargs['ray_start'] = ray_start

    os.makedirs(outdir, exist_ok=True)

    ws = load_latent(latent, device=device)
    print(f'Loaded projected latent from "{latent}" with shape {tuple(ws.shape)}')

    delta_c = None if no_delta_c else compute_delta_c(G, cfg=cfg, device=device)

    for yaw, pitch in zip(yaws, pitchs):
        fname = os.path.join(outdir, f'render_yaw{yaw:+.2f}_pitch{pitch:+.2f}.png')
        img = render_angle(
            G=G,
            ws=ws,
            yaw_deg=yaw,
            pitch_deg=pitch,
            delta_c=delta_c,
            cfg=cfg,
            image_mode=image_mode,
            device=device,
        )
        PIL.Image.fromarray(img, 'RGB').save(fname)
        print(f'Saved "{fname}"')

#----------------------------------------------------------------------------

if __name__ == "__main__":
    generate_images() # pylint: disable=no-value-for-parameter

